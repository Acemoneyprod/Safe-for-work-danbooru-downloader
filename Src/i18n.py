def _load_translations():
    global _TRANSLATIONS
    if _TRANSLATIONS is not None:
        return _TRANSLATIONS
    import json
    import os
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "translations.json")
    try:
        with open(path, "r", encoding="utf-8") as f:
            _TRANSLATIONS = json.load(f)
    except Exception:
        _TRANSLATIONS = {}
    return _TRANSLATIONS


def tr(text):
    if _current == "en" or not text:
        return text
    data = _load_translations().get(_current)
    if not data:
        return text
    return data.get(text) or text


def _src(w, attr, getter):
    if not hasattr(w, attr):
        setattr(w, attr, getter())
    return getattr(w, attr)


def translate_widgets(root):
    from PySide6 import QtWidgets
    widgets = [root] + root.findChildren(QtWidgets.QWidget)
    for w in widgets:
        try:
            if getattr(w, "_i18n_dynamic", False):
                continue
            if isinstance(w, QtWidgets.QLabel):
                src = _src(w, "_i18n_text", w.text)
                if (src and src not in NO_TRANSLATE
                        and "<" not in src and ">" not in src):
                    w.setText(tr(src))
            elif isinstance(w, QtWidgets.QPushButton):
                src = _src(w, "_i18n_text", w.text)
                stripped = src.strip()
                if stripped:
                    lead = src[:len(src) - len(src.lstrip())]
                    trail = src[len(src.rstrip()):]
                    w.setText(lead + tr(stripped) + trail)
            elif isinstance(w, QtWidgets.QLineEdit):
                src = _src(w, "_i18n_ph", w.placeholderText)
                if src:
                    w.setPlaceholderText(tr(src))
            elif isinstance(w, QtWidgets.QComboBox):
                if not hasattr(w, "_i18n_items"):
                    w._i18n_items = [w.itemText(i) for i in range(w.count())]
                for i, src in enumerate(w._i18n_items):
                    if i < w.count():
                        w.setItemText(i, tr(src))
            src = _src(w, "_i18n_tip", w.toolTip)
            if src:
                w.setToolTip(tr(src))
        except Exception:
            pass


